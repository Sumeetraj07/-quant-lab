# BacktestConfig — complete configuration for a backtest run
# =============================================================================

@dataclass(frozen=True)
class BacktestConfig:
    """
    Complete, immutable configuration for a single backtest run.

    All parameters needed to reproduce the backtest are stored here.
    This object is serialized and stored in the experiments table.

    Note: Changing any field produces a different experiment.
    """

    strategy_id: str
    parameters: dict[str, Any]
    symbols: list[str]
    start_date: date
    end_date: date
    timeframe: str                              # e.g. "1d"
    initial_capital: float
    commission_rate: float                      # e.g. 0.001 = 0.1%
    slippage_bps: float                         # basis points, e.g. 5.0 = 5 bps
    spread_bps: float                           # half-spread each side, e.g. 2.0
    position_sizing: PositionSizingMethod
    sizing_parameter: float = 1.0              # Qty / capital / pct depending on method
    benchmark_symbol: str | None = None
    risk_free_rate: float = 0.0                # Annual, e.g. 0.05 = 5%
    data_source: str = "alpha_vantage"
    adjusted_prices: bool = True
    experiment_id: str | None = None
    notes: str = ""
    seed: int | None = None                    # For reproducibility in Monte Carlo

    def __post_init__(self) -> None:
        if self.initial_capital <= 0:
            raise ValueError(f"initial_capital must be positive, got {self.initial_capital}")
        if self.start_date >= self.end_date:
            raise ValueError(
                f"start_date ({self.start_date}) must be before end_date ({self.end_date})"
            )
        if not self.symbols:
            raise ValueError("symbols list cannot be empty")

    def to_dict(self) -> dict[str, Any]:
        """Serialize to a JSON-compatible dict for storage."""
        return {
            "strategy_id": self.strategy_id,
            "parameters": self.parameters,
            "symbols": self.symbols,
            "start_date": str(self.start_date),
            "end_date": str(self.end_date),
            "timeframe": self.timeframe,
            "initial_capital": self.initial_capital,
            "commission_rate": self.commission_rate,
            "slippage_bps": self.slippage_bps,
            "spread_bps": self.spread_bps,
            "position_sizing": self.position_sizing.value,
            "sizing_parameter": self.sizing_parameter,
            "benchmark_symbol": self.benchmark_symbol,
            "risk_free_rate": self.risk_free_rate,
            "data_source": self.data_source,
            "adjusted_prices": self.adjusted_prices,
            "experiment_id": self.experiment_id,
            "notes": self.notes,
            "seed": self.seed,
        }


