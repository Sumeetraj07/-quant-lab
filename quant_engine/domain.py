# PerformanceMetrics — full performance report
# =============================================================================

@dataclass
class PerformanceMetrics:
    """
    Comprehensive performance metrics for a backtest or strategy period.

    All metrics are computed by the metrics engine from actual trade/equity data.
    None of these values are estimated or invented.

    Annualization uses 252 trading days per year.
    """

    # --- Return metrics ---
    total_return: float             # e.g. 0.45 = 45%
    cagr: float                     # Compound Annual Growth Rate
    annualized_return: float        # Same as CAGR for daily data
    annualized_volatility: float    # Annualized std dev of daily returns

    # --- Risk-adjusted returns ---
    sharpe_ratio: float             # (Return - Rf) / Volatility
    sortino_ratio: float            # (Return - Rf) / Downside deviation
    calmar_ratio: float             # CAGR / Max Drawdown

    # --- Drawdown ---
    max_drawdown: float             # e.g. -0.25 = -25%
    max_drawdown_duration: int      # In calendar days
    recovery_time: int | None       # Days to recover from max DD (None if not recovered)

    # --- Trade statistics ---
    total_trades: int
    winning_trades: int
    losing_trades: int
    win_rate: float                 # Winning trades / total trades
    profit_factor: float            # Gross profit / Gross loss (>1 = profitable)
    avg_trade: float                # Average net PnL per trade
    best_trade: float               # Best single net PnL
    worst_trade: float              # Worst single net PnL
    avg_winning_trade: float
    avg_losing_trade: float

    # --- Efficiency ---
    turnover: float                 # Annual portfolio turnover rate

    # --- Time-series data (optional, for charts) ---
    daily_returns: pd.Series | None = None
    monthly_returns: pd.Series | None = None
    yearly_returns: pd.Series | None = None
    rolling_sharpe: pd.Series | None = None

    def to_dict(self) -> dict[str, Any]:
        """JSON-serializable summary (excludes Series fields)."""
        return {
            "total_return": round(self.total_return, 6),
            "cagr": round(self.cagr, 6),
            "annualized_return": round(self.annualized_return, 6),
            "annualized_volatility": round(self.annualized_volatility, 6),
            "sharpe_ratio": round(self.sharpe_ratio, 4),
            "sortino_ratio": round(self.sortino_ratio, 4),
            "calmar_ratio": round(self.calmar_ratio, 4),
            "max_drawdown": round(self.max_drawdown, 6),
            "max_drawdown_duration": self.max_drawdown_duration,
            "recovery_time": self.recovery_time,
            "total_trades": self.total_trades,
            "winning_trades": self.winning_trades,
            "losing_trades": self.losing_trades,
            "win_rate": round(self.win_rate, 4),
            "profit_factor": round(self.profit_factor, 4),
            "avg_trade": round(self.avg_trade, 4),
            "best_trade": round(self.best_trade, 4),
            "worst_trade": round(self.worst_trade, 4),
            "avg_winning_trade": round(self.avg_winning_trade, 4),
            "avg_losing_trade": round(self.avg_losing_trade, 4),
            "turnover": round(self.turnover, 4),
        }

    def __repr__(self) -> str:
        return (
            f"PerformanceMetrics("
            f"total_return={self.total_return:.1%} "
            f"cagr={self.cagr:.1%} "
            f"sharpe={self.sharpe_ratio:.2f} "
            f"max_dd={self.max_drawdown:.1%} "
            f"trades={self.total_trades})"
        )


# =============================================================================
# BacktestResult — complete output of a backtest run
# =============================================================================

@dataclass
class BacktestResult:
    """
    Complete, immutable output of a backtest run.

    Contains everything needed to:
    - Display results in the dashboard
    - Compare strategies
    - Store in the database
    - Reproduce the experiment

    Temporal consistency guaranteed: all data was generated by the
    event-driven engine with strict temporal ordering.
    """

    config: BacktestConfig
    metrics: PerformanceMetrics
    equity_curve: pd.Series                    # DatetimeIndex → portfolio equity
    drawdown_series: pd.Series                 # DatetimeIndex → drawdown fraction
    trades: list[Trade]
    portfolio_snapshots: list[dict[str, Any]]  # One per bar
    benchmark_metrics: PerformanceMetrics | None = None
    benchmark_equity_curve: pd.Series | None = None
    warnings: list[str] = field(default_factory=list)
    run_duration_seconds: float = 0.0

    def summary(self) -> str:
        """Human-readable summary of results."""
        m = self.metrics
        lines = [
            f"BacktestResult: {self.config.strategy_id}",
            f"  Period:     {self.config.start_date} → {self.config.end_date}",
            f"  Symbols:    {', '.join(self.config.symbols)}",
            f"  Capital:    ${self.config.initial_capital:,.0f}",
            "  " + "─" * 40,
            f"  Total Return:    {m.total_return:.2%}",
            f"  CAGR:            {m.cagr:.2%}",
            f"  Sharpe Ratio:    {m.sharpe_ratio:.2f}",
            f"  Sortino Ratio:   {m.sortino_ratio:.2f}",
            f"  Calmar Ratio:    {m.calmar_ratio:.2f}",
            f"  Max Drawdown:    {m.max_drawdown:.2%}",
            f"  Ann. Volatility: {m.annualized_volatility:.2%}",
            "  " + "─" * 40,
            f"  Total Trades:    {m.total_trades}",
            f"  Win Rate:        {m.win_rate:.1%}",
            f"  Profit Factor:   {m.profit_factor:.2f}",
            f"  Best Trade:      ${m.best_trade:,.2f}",
            f"  Worst Trade:     ${m.worst_trade:,.2f}",
        ]
        if self.warnings:
            lines.append("  " + "─" * 40)
            lines.append(f"  Warnings: {len(self.warnings)}")
            for w in self.warnings:
                lines.append(f"    ⚠ {w}")
        return "\n".join(lines)
